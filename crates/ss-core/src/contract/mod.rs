//! Owner-only: lanes never edit this module (README D2); a change goes to the Owner, who edits the
//! `contract-*.md` file and this module in one commit and regenerates `crates/ss-core/bindings/`
//! with `SS_WRITE_BINDINGS=1 cargo test -p ss-core --test contract_test`.

pub mod error;
pub mod ipc;
pub mod sidecar;

use std::collections::BTreeSet;
use std::path::Path;

use ts_rs::{Config, ExportError, TS};

pub use error::{AppError, ErrorKind};

/// Returned by `get_app_info` and sent in the sidecar `initialize`.
pub const CONTRACT_VERSION: i64 = 1;

/// SQLite schema v1, verbatim from contract-sqlite-schema.md.
pub const MIGRATION_0001_INIT: &str = include_str!("../../../../contracts/sqlite/0001_init.sql");

/// Who asks for a write (contract-tauri-ipc rule 8). Every `ss-core` write API takes one.
/// A file write whose source or destination lies under a protected root, or under any path
/// containing `\OneDrive\`, is allowed only for [`Caller::Ui`]; [`Caller::Cli`] gets `protectedRoot`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Caller {
    /// A Tauri command (the user acted in the app).
    Ui,
    /// `ssctl`.
    Cli,
}

/// File name of the generated command table inside the bindings dir.
pub const COMMANDS_TS_FILE: &str = "commands.ts";

/// Writes every contract TS binding (ts-rs, with dependencies) plus `commands.ts` into `dir`.
/// The ONLY binding writer: there is no `#[ts(export)]` attribute anywhere, so a plain
/// `cargo test` never rewrites the committed `bindings/` dir.
pub fn export_bindings(dir: &Path) -> Result<(), ExportError> {
    let cfg = Config::new().with_out_dir(dir);
    macro_rules! export {
        ($($t:ty),* $(,)?) => { $( <$t as TS>::export_all(&cfg)?; )* };
    }
    use ipc::*;
    use sidecar::*;
    export!(
        AppError, ErrorKind,
        // shared + results
        AppInfo, LibraryRoot, ImageSummary, ImageDetail, ImageQuery, ImagePage, OpResult, OpFailure,
        SidecarStatus, AppWarning, JobStarted, SmartFilter, CatalogCounts, CountBy, Stats, SettingsMap,
        Tag, AlbumRef, Album, CategoryScore, TimelineResult, RenamePreview, PermanentDeleteTicket,
        JournalPage, DuplicateResult, SessionsResult, IssuesResult, PiiResult, SettingKey, AiDevice,
        EditMode, ImageFormat,
        // requests
        AddLibraryRootReq, RemoveLibraryRootReq, StartIndexReq, DownloadCloudOnlyReq, CancelJobReq,
        GetImageReq, GetTimelineReq, SetSettingReq, CreateTagReq, UpdateTagReq, DeleteTagReq, SetTagsReq,
        CreateAlbumReq, RenameAlbumReq, DeleteAlbumReq, AlbumImagesReq, SetFavoriteReq, SetRatingReq,
        SetNoteReq, SaveSmartFilterReq, DeleteSmartFilterReq, MoveImagesReq, PreviewRenameReq,
        RenameImagesReq, ImageIdsReq, DeletePermanentlyReq, UndoReq, LimitReq, StartAiReq,
        FindDuplicatesReq, GetSessionsReq, DetectIssuesReq, ImageIdReq, ConvertImagesReq,
        StitchImagesReq, ExportZipReq, ExportPdfReq,
        // events
        JobProgress, LibraryChanged, NewScreenshot, OpenImage,
        // sidecar (exported under sidecar/)
        RpcRequest, RpcResponse<EmptyObject>, RpcErrorResponse, RpcNotification, InitializeResult,
        OcrRecognizeResult, EmbedImagesResult, EmbedTextResult, ClassifyZeroShotResult,
        ColorDominantResult, PiiDetectResult,
    );
    std::fs::write(dir.join(COMMANDS_TS_FILE), commands_ts())?;
    Ok(())
}

/// TS source of `bindings/commands.ts`: the typed command map and the runtime command list,
/// generated from [`ipc::COMMANDS`] so the UI never hand-mirrors the command table.
pub fn commands_ts() -> String {
    let mut idents = BTreeSet::new();
    for c in ipc::COMMANDS {
        for ty in c.req.into_iter().chain([c.res]) {
            idents.extend(type_idents(ty));
        }
    }
    let mut out = String::from(
        "// Generated from ss_core::contract::ipc::COMMANDS by contract_test.rs. Do not edit this file manually.\n",
    );
    for id in &idents {
        out.push_str(&format!("import type {{ {id} }} from \"./{id}\";\n"));
    }
    out.push_str(&format!("\nexport const CONTRACT_VERSION = {CONTRACT_VERSION};\n\n"));
    out.push_str("export type CommandMap = {\n");
    for c in ipc::COMMANDS {
        let req = c.req.unwrap_or("null");
        out.push_str(&format!("  {}: {{ req: {}; res: {} }};\n", c.name, req, c.res));
    }
    out.push_str("};\n\nexport type CommandName = keyof CommandMap;\n\n");
    out.push_str("export const COMMANDS = [\n");
    for c in ipc::COMMANDS {
        out.push_str(&format!(
            "  {{ name: \"{}\", hasReq: {}, rawBody: {} }},\n",
            c.name,
            c.req.is_some(),
            c.raw_body
        ));
    }
    out.push_str("] as const;\n");
    out
}

/// Binding type names referenced by a TS type expression such as `Tag[]` or `ImagePage`.
pub fn type_idents(ty: &str) -> Vec<String> {
    ty.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| w.starts_with(|c: char| c.is_ascii_uppercase()))
        .map(str::to_owned)
        .collect()
}
